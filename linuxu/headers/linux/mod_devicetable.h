/* PCI device table (subset) */
struct pci_device_id {
	__u16 vendor, device;
	__u16 subsys_vendor, subsys_device;
	__u32 class, class_mask;
	unsigned long driver_data;
};

#define PCI_DEVICE_ID_ANY		0xffffU
#define PCI_DEVICE_ID_NONE		0x0000U
#define PCI_VENDOR_ID_ANY		0xffffU
#define PCI_VENDOR_ID_NONE		0x0000U

#define PCI_DEVICE(vend, devid) \
	.vendor = (vend), .device = (devid), \
	.subsys_vendor = PCI_ANY_ID, .subsys_device = PCI_ANY_ID
#define PCI_VENDOR(vend) \
	.vendor = (vend), .device = PCI_ANY_ID, \
	.subsys_vendor = PCI_ANY_ID, .subsys_device = PCI_ANY_ID
#define PCI_DEVICE_CLASS(_class, _mask) \
	.vendor = PCI_ANY_ID, .device = PCI_ANY_ID, \
	.subsys_vendor = PCI_ANY_ID, .subsys_device = PCI_ANY_ID, \
	.class = (_class), .class_mask = (_mask)

